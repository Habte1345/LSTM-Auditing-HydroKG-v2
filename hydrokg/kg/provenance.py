"""PROV-O provenance of every artefact in an experiment, and the leakage check.

Every dataset carries the period it covers (hk:periodStart/hk:periodEnd) and the basin set
it refers to. An entity generated by an activity is derived (prov:wasDerivedFrom) from
everything that activity used. The leakage check is a single SPARQL query: an evaluated
prediction set leaks if it is transitively derived from discharge observations whose
period overlaps its own and whose basin set includes its basins.
"""

from __future__ import annotations

import itertools
from typing import Iterable, Optional

import pandas as pd
from rdflib import RDF, RDFS, XSD, Graph, Literal, URIRef
from rdflib.namespace import PROV

from hydrokg.kg.graph import HK

LEAKAGE_QUERY = """PREFIX hk: <https://w3id.org/hydrokg#> PREFIX prov: <http://www.w3.org/ns/prov#>
SELECT DISTINCT ?prediction ?observations ?ps ?pe ?os ?oe WHERE {
  ?prediction a hk:EvaluatedPredictionSet ; hk:periodStart ?ps ; hk:periodEnd ?pe ; hk:basinSet ?pb .
  ?prediction prov:wasDerivedFrom+ ?observations .
  ?observations a hk:DischargeObservations ; hk:periodStart ?os ; hk:periodEnd ?oe ; hk:basinSet ?ob .
  FILTER(?os <= ?pe && ?oe >= ?ps)
  FILTER(?ob = "all" || ?pb = "all" || ?ob = ?pb)
}"""


class Provenance:
    def __init__(self, g: Graph, namespace: str):
        self.g = g
        self.ns = namespace.rstrip("/") + "/"
        self._counter = itertools.count()

    def _iri(self, label: str) -> URIRef:
        safe = "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in label)
        return URIRef(f"{self.ns}{safe}")

    def _period(self, node: URIRef, period: Optional[tuple]) -> None:
        if period is not None:
            self.g.add((node, HK.periodStart, Literal(pd.Timestamp(period[0]).date(), datatype=XSD.date)))
            self.g.add((node, HK.periodEnd, Literal(pd.Timestamp(period[1]).date(), datatype=XSD.date)))

    def dataset(self, kind: URIRef, label: str, period: Optional[tuple] = None,
                basin_set: str = "all") -> URIRef:
        node = self._iri(label)
        self.g.add((node, RDF.type, kind))
        self.g.add((node, RDFS.label, Literal(label)))
        self.g.add((node, HK.basinSet, Literal(basin_set)))
        self._period(node, period)
        return node

    def activity(self, kind: URIRef, label: str, used: Iterable[URIRef] = (),
                 **properties) -> URIRef:
        node = self._iri(label)
        self.g.add((node, RDF.type, kind))
        self.g.add((node, RDFS.label, Literal(label)))
        for u in used:
            self.g.add((node, PROV.used, u))
        for key, value in properties.items():
            if value is not None:
                self.g.add((node, HK[key], Literal(value)))
        return node

    def entity(self, kind: URIRef, label: str, generated_by: URIRef,
               period: Optional[tuple] = None, basin_set: str = "all", **properties) -> URIRef:
        node = self._iri(label)
        self.g.add((node, RDF.type, kind))
        self.g.add((node, RDFS.label, Literal(label)))
        self.g.add((node, PROV.wasGeneratedBy, generated_by))
        self.g.add((node, HK.basinSet, Literal(basin_set)))
        self._period(node, period)
        for used in self.g.objects(generated_by, PROV.used):
            self.g.add((node, PROV.wasDerivedFrom, used))
        for key, value in properties.items():
            if value is not None:
                self.g.add((node, HK[key], Literal(value)))
        return node


SPATIAL_LEAKAGE_QUERY = """PREFIX hk: <https://w3id.org/hydrokg#> PREFIX prov: <http://www.w3.org/ns/prov#>
SELECT DISTINCT ?prediction ?observations ?ps ?pe ?os ?oe WHERE {
  ?prediction a hk:EvaluatedPredictionSet ; hk:basinSet "test" ; hk:periodStart ?ps ; hk:periodEnd ?pe .
  ?prediction prov:wasDerivedFrom+ ?observations .
  ?observations a hk:DischargeObservations ; hk:basinSet ?ob ; hk:periodStart ?os ; hk:periodEnd ?oe .
  FILTER(?ob = "test" || ?ob = "all")
}"""


def leakage_report(g: Graph, basin_holdout: bool = False) -> pd.DataFrame:
    """Temporal leakage always; spatial leakage (held-out basins' discharge at any time)
    when `basin_holdout`."""
    queries = [("temporal", LEAKAGE_QUERY)] + ([("spatial", SPATIAL_LEAKAGE_QUERY)] if basin_holdout else [])
    rows = []
    for kind, query in queries:
        for p, o, ps, pe, os_, oe in g.query(query):
            rows.append({"kind": kind, "prediction": str(p), "observations": str(o),
                         "prediction_period": f"{ps}..{pe}", "observation_period": f"{os_}..{oe}"})
    return pd.DataFrame(rows, columns=["kind", "prediction", "observations", "prediction_period",
                                       "observation_period"])


def assert_no_leakage(g: Graph, basin_holdout: bool = False) -> None:
    report = leakage_report(g, basin_holdout)
    if len(report):
        raise RuntimeError("Provenance shows evaluated predictions derived from overlapping "
                           f"discharge observations:\n{report.to_string(index=False)}")
